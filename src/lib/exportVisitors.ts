import { Visitor } from "@/types/visitor";
import { format } from "date-fns";

function formatVisitorForExport(visitor: Visitor) {
  return {
    "First Name": visitor.firstName,
    "Surname": visitor.surname,
    "Email": visitor.email,
    "Mobile": visitor.mobile,
    "Type": visitor.type,
    "Address": visitor.address || "",
    "Check-In": format(visitor.checkInTime, "dd/MM/yyyy HH:mm"),
    "Check-Out": visitor.checkOutTime ? format(visitor.checkOutTime, "dd/MM/yyyy HH:mm") : "",
    "Status": visitor.status === "checked-in" ? "Checked In" : "Checked Out",
    "Visiting": visitor.whomToVisit || "",
    "Additional Visitors": String(visitor.additionalVisitors),
    "Comments": visitor.comments || "",
    "Check-in Declaration": visitor.healthDeclaration ? "Yes" : "No",
    "Body Temperature": visitor.bodyTemperature ? `${visitor.bodyTemperature}°C` : "",
    "Influenza Vaccine Date": visitor.influenzaVaccineDate || "",
    "COVID Dose 1 Date": visitor.covidDose1Date || "",
    "COVID Dose 2 Date": visitor.covidDose2Date || "",
    "Privacy Acknowledged": visitor.acknowledgedPrivacy ? "Yes" : "No",
    "Retention Expiry": format(visitor.retentionExpiry, "dd/MM/yyyy"),
  };
}

export function exportVisitorsToCSV(visitors: Visitor[], filename?: string) {
  const rows = visitors.map(formatVisitorForExport);
  if (rows.length === 0) return;

  const headers = Object.keys(rows[0]);
  const csvContent = [
    headers.join(","),
    ...rows.map((row) =>
      headers.map((h) => `"${(row as Record<string, string>)[h].replace(/"/g, '""')}"`).join(",")
    ),
  ].join("\n");

  const blob = new Blob([csvContent], { type: "text/csv;charset=utf-8;" });
  downloadBlob(blob, filename || `visitor-export-${format(new Date(), "yyyy-MM-dd")}.csv`);
}

